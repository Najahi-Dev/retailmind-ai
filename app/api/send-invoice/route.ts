import { NextResponse } from "next/server";
import { Resend } from "resend";

const resendApiKey = process.env.RESEND_API_KEY;
const resend = resendApiKey ? new Resend(resendApiKey) : null;

export async function POST(req: Request) {
  try {
    const body = await req.json();
    const {
      recipientEmail,
      invoiceNumber,
      poNumber,
      supplierName,
      totalValue,
      lineItems,
    } = body;

    const email = recipientEmail || "mohamedashan070@gmail.com";
    const invoiceNo = invoiceNumber || `INV-${poNumber?.replace(/^PO-/, "") || "1001"}`;

    const lineItemsHtml = (lineItems || [])
      .map(
        (item: any) => `
        <tr>
          <td style="padding: 10px; border-bottom: 1px solid #e2e8f0; font-weight: bold;">${item.productName || "Product Item"}</td>
          <td style="padding: 10px; border-bottom: 1px solid #e2e8f0; font-family: monospace;">${item.sku || "SKU-ITEM"}</td>
          <td style="padding: 10px; border-bottom: 1px solid #e2e8f0; text-align: center;">${item.quantityOrdered || 1}</td>
          <td style="padding: 10px; border-bottom: 1px solid #e2e8f0; text-align: right; font-family: monospace; font-weight: bold; color: #4f46e5;">LKR ${(item.lineTotal || item.unitCost * item.quantityOrdered || 0).toLocaleString()}</td>
        </tr>
      `
      )
      .join("");

    const htmlContent = `
      <!DOCTYPE html>
      <html>
      <head>
        <meta charset="utf-8">
        <title>Commercial Invoice ${invoiceNo}</title>
      </head>
      <body style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; background-color: #f8fafc; margin: 0; padding: 20px; color: #0f172a;">
        <div style="max-width: 600px; margin: 0 auto; background: #ffffff; border-radius: 16px; overflow: hidden; border: 1px solid #e2e8f0; box-shadow: 0 10px 15px -3px rgba(0,0,0,0.1);">
          <!-- Header -->
          <div style="background: linear-gradient(135deg, #0f172a 0%, #1e1b4b 100%); padding: 30px; color: #ffffff; text-align: left;">
            <h1 style="margin: 0; font-size: 22px; font-weight: 800; letter-spacing: -0.5px;">RetailMind AI</h1>
            <p style="margin: 4px 0 0 0; font-size: 12px; color: #cbd5e1;">Tax Commercial Purchase Order Invoice</p>
          </div>

          <!-- Invoice Details -->
          <div style="padding: 30px;">
            <div style="display: flex; justify-content: space-between; border-bottom: 2px solid #f1f5f9; pb-20px; margin-bottom: 20px;">
              <div>
                <span style="font-size: 10px; font-weight: 800; text-transform: uppercase; color: #6366f1; letter-spacing: 1px;">Invoice Number</span>
                <h2 style="margin: 4px 0 0 0; font-size: 20px; font-family: monospace; color: #0f172a;">${invoiceNo}</h2>
                <p style="margin: 4px 0 0 0; font-size: 12px; color: #64748b;">PO Reference: <strong>${poNumber}</strong></p>
              </div>
              <div style="text-align: right;">
                <span style="font-size: 10px; font-weight: 800; text-transform: uppercase; color: #64748b; letter-spacing: 1px;">Issued To</span>
                <h3 style="margin: 4px 0 0 0; font-size: 14px; color: #0f172a;">${supplierName || "Vendor Supplier"}</h3>
                <p style="margin: 4px 0 0 0; font-size: 12px; color: #64748b;">Date: ${new Date().toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" })}</p>
              </div>
            </div>

            <!-- Table -->
            <table style="width: 100%; border-collapse: collapse; font-size: 12px; margin-bottom: 24px;">
              <thead>
                <tr style="background: #f8fafc; color: #475569; font-weight: 700; text-align: left;">
                  <th style="padding: 10px;">Item</th>
                  <th style="padding: 10px;">SKU</th>
                  <th style="padding: 10px; text-align: center;">Qty</th>
                  <th style="padding: 10px; text-align: right;">Total</th>
                </tr>
              </thead>
              <tbody>
                ${lineItemsHtml}
              </tbody>
            </table>

            <!-- Grand Total -->
            <div style="background: #f1f5f9; border-radius: 12px; padding: 16px; text-align: right; margin-bottom: 24px;">
              <span style="font-size: 12px; color: #475569; font-weight: 600;">Total Invoice Valuation:</span>
              <h3 style="margin: 4px 0 0 0; font-size: 22px; font-family: monospace; color: #4f46e5; font-weight: 800;">LKR ${Number(totalValue || 0).toLocaleString()}</h3>
            </div>

            <p style="font-size: 11px; color: #94a3b8; text-align: center; margin: 0;">
              This is an automated purchase order commercial invoice generated by RetailMind AI Supermarket Operations.
            </p>
          </div>
        </div>
      </body>
      </html>
    `;

    if (resend) {
      const data = await resend.emails.send({
        from: "RetailMind AI <onboarding@resend.dev>",
        to: [email],
        subject: `[Commercial Invoice] ${invoiceNo} for ${poNumber}`,
        html: htmlContent,
      });

      return NextResponse.json({ success: true, method: "resend", data });
    }

    // Fallback response when Resend API key is not yet set in environment
    return NextResponse.json({
      success: true,
      method: "simulation",
      recipientEmail: email,
      message: `Invoice ${invoiceNo} prepared and dispatched to ${email}`,
    });
  } catch (err) {
    console.error("Failed to send invoice email:", err);
    return NextResponse.json(
      { success: false, error: err instanceof Error ? err.message : "Failed to dispatch email" },
      { status: 500 }
    );
  }
}
